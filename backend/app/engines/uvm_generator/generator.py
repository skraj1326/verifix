    def _parse_width(self, width_str: str) -> str:
        """Parse width string and return bit width."""
        if not width_str:
            return "0"
        import re
        match = re.match(r"\[(\d+):(\d+)\]", width_str)
        if match:
            msb = int(match.group(1))
            lsb = int(match.group(2))
            return str(msb - lsb)
        return "0"